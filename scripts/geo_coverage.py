"""Geo coverage report: per flights2015 destination, the procedures tier, surface tier, stand count and whether
2015 ground movements exist.

Usage: python3 scripts/geo_coverage.py        (writes data/ref/GEO_COVERAGE.md)
"""
import gzip
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from backend.datastore import FileStore  # noqa: E402
from backend.geo import store  # noqa: E402
from backend.wave.icao import iata_for  # noqa: E402
from scripts.fetch_cifp import airports  # noqa: E402

OUT = ROOT / "data" / "ref" / "GEO_COVERAGE.md"
REAL_REACH = 0.8   # airport-level approximation of the per-wave surface quality gate (decided per wave in T24)


def _surface_tier(doc: dict | None) -> str:
    if doc is None:
        return "none"
    reach = (doc.get("quality") or {}).get("reach_pct") or {}
    if doc.get("stands") and reach and all(v >= REAL_REACH for v in reach.values()):
        return "real"
    return "generic"


def _doc(blob: bytes | None) -> dict | None:
    return None if blob is None else json.loads(gzip.decompress(blob))


def coverage() -> list[dict]:
    """Always reads the derived files (FileStore), never a database, so the report is the same on every machine."""
    fs = FileStore()
    rows = []
    for icao in airports():
        iata = iata_for(icao)
        proc = _doc(fs.procedures(icao))
        surf = _doc(fs.surface(icao))
        rows.append({
            "iata": iata, "icao": icao,
            "procedures_tier": "none" if proc is None else proc["header"].get("tier", "none"),
            "surface_tier": _surface_tier(surf),
            "stands": 0 if surf is None else len(surf.get("stands") or []),
            # database-only dataset: the constant, not file presence, so the report is identical on every machine
            "movements": iata in store.MOVEMENT_AIRPORTS,
        })
    return sorted(rows, key=lambda r: r["iata"])


def _count(rows: list[dict], key: str) -> dict[str, int]:
    out: dict[str, int] = {}
    for r in rows:
        out[r[key]] = out.get(r[key], 0) + 1
    return dict(sorted(out.items()))


def markdown(rows: list[dict]) -> str:
    def fmt(r: dict) -> str:
        return f"| {r['iata']} | {r['icao']} | {r['procedures_tier']} | {r['surface_tier']} | {r['stands']} | {'yes' if r['movements'] else 'no'} |"
    head = "| IATA | ICAO | Procedures | Surface | Stands | Movements |\n|---|---|---|---|---|---|"
    top = [r for r in rows if r["iata"] in store.TOP30]
    lines = ["# Geo coverage", "",
             "Generated by `python3 scripts/geo_coverage.py`. Procedures: FAA CIFP 2611, not for navigation. "
             "Surface: (c) OpenStreetMap contributors (ODbL). Surface `real` = every runway end reaches >= 80 % of stands.", "",
             "## Totals", "", f"- Destinations: {len(rows)}"]
    lines += [f"- Procedures {k}: {v}" for k, v in _count(rows, "procedures_tier").items()]
    lines += [f"- Surface {k}: {v}" for k, v in _count(rows, "surface_tier").items()]
    lines += [f"- Movements (2015, database-only): {sum(r['movements'] for r in rows)}", "",
              "## Top 30 by 2015 arrivals", "", head, *map(fmt, top), "", "## All destinations", "", head, *map(fmt, rows), ""]
    return "\n".join(lines)


def main() -> None:
    rows = coverage()
    OUT.write_text(markdown(rows))
    print(f"wrote {OUT} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
